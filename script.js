const accordion = document.getElementById("pwaAccordion");
const searchInput = document.getElementById("veilleSearch");

if (accordion) {
  accordion.innerHTML = veilleData
    .map(
      (item, index) => `
        <div class="accordion-item">
          <h2 class="accordion-header" id="heading-${index}">
            <button
              class="accordion-button ${index === 0 ? "" : "collapsed"}"
              type="button"
              data-bs-toggle="collapse"
              data-bs-target="#collapse-${index}"
              aria-expanded="${index === 0 ? "true" : "false"}"
              aria-controls="collapse-${index}"
            >
              <div class="accordion-title-wrap">
                <span class="accordion-number">Veille ${index + 1}</span>
                <span class="accordion-title-text">${item.title}</span>
              </div>
            </button>
          </h2>
          <div
            id="collapse-${index}"
            class="accordion-collapse collapse ${index === 0 ? "show" : ""}"
            aria-labelledby="heading-${index}"
            data-bs-parent="#pwaAccordion"
          >
            <div class="accordion-body">
              <div class="card">
                <h3>Définition</h3>
                <p>${item.definition}</p>
                <ul>
                  ${item.points.map((point) => `<li>${point}</li>`).join("")}
                </ul>
                <p><strong>Conclusion :</strong> ${item.conclusion}</p>
                <a
                  class="btn-veille"
                  href="${item.link}"
                  target="_blank"
                  rel="noopener noreferrer"
                >
                  Voir la veille
                </a>
              </div>
            </div>
          </div>
        </div>
      `
    )
    .join("");
}

if (searchInput) {
  searchInput.addEventListener("input", (event) => {
    const query = event.target.value.trim().toLowerCase();
    const items = document.querySelectorAll(".accordion-item");

    items.forEach((item) => {
      const text = item.textContent.toLowerCase();
      const matches = !query || text.includes(query);
      item.classList.toggle("hidden-by-search", !matches);
    });
  });
}
